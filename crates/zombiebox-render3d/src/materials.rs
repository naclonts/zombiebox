//! Retro vertex-color palettes for county districts and building styles.
use glam::Vec4;
use zombiebox_core::{BuildingStyle, District};

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct RetroMaterial {
    pub wall_lit: Vec4,
    pub wall_shade: Vec4,
    pub trim: Vec4,
    pub course: Vec4,
    pub plinth: Vec4,
    pub roof_front: Vec4,
    pub roof_side: Vec4,
    pub roof_back: Vec4,
    pub roof_ridge: Vec4,
    pub roof_eave: Vec4,
    pub carpet: Vec4,
    pub carpet_trim: Vec4,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DistrictPalette {
    pub ground: Vec4,
    pub foliage: Vec4,
    pub foliage_shade: Vec4,
    pub road: Vec4,
    pub sidewalk: Vec4,
    pub accent: Vec4,
}

const fn c(r: u8, g: u8, b: u8) -> Vec4 {
    Vec4::new(r as f32 / 255., g as f32 / 255., b as f32 / 255., 1.)
}
#[allow(clippy::too_many_arguments)]
const fn m(
    w: Vec4,
    s: Vec4,
    t: Vec4,
    co: Vec4,
    p: Vec4,
    rf: Vec4,
    rs: Vec4,
    rb: Vec4,
    rr: Vec4,
    re: Vec4,
    ca: Vec4,
    ct: Vec4,
) -> RetroMaterial {
    RetroMaterial {
        wall_lit: w,
        wall_shade: s,
        trim: t,
        course: co,
        plinth: p,
        roof_front: rf,
        roof_side: rs,
        roof_back: rb,
        roof_ridge: rr,
        roof_eave: re,
        carpet: ca,
        carpet_trim: ct,
    }
}

