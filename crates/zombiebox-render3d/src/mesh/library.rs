//! Runtime mesh library for the checked-in living-building prototypes.
//!
//! The binary format is deliberately tiny: `ZBPM`, vertex count, index count,
//! followed by 28-byte vertices (position, normal, RGBA8) and u16 indices.
//! Keeping decoding here means normal game builds never need a model loader.

use super::{MeshBuffer, VertexMeta, WorldVertex, kit, signage};
use crate::coords::sim_to_render_point;
use glam::{Mat4, Vec3};
use std::{collections::BTreeMap, sync::OnceLock};
use zombiebox_core::{PropFacing, PropId, PropState, PropView};

#[derive(Clone, Debug)]
pub struct Prototype {
    pub mesh: MeshBuffer,
}

/// Decode one checked-in `.mesh` asset.
fn decode(name: &str, bytes: &[u8]) -> Result<Prototype, String> {
    if bytes.len() < 12 || &bytes[..4] != b"ZBPM" {
        return Err(format!("{name}: invalid ZBPM header"));
    }
    let v = u32::from_le_bytes(bytes[4..8].try_into().unwrap()) as usize;
    let n = u32::from_le_bytes(bytes[8..12].try_into().unwrap()) as usize;
    let end = 12usize
        .checked_add(v.checked_mul(28).ok_or("vertex overflow")?)
        .and_then(|x| x.checked_add(n.checked_mul(2)?))
        .ok_or("mesh overflow")?;
    if end != bytes.len() || n % 3 != 0 {
        return Err(format!("{name}: truncated mesh"));
    }
    let mut mesh = MeshBuffer::with_capacity(v, n);
    for i in 0..v {
        let o = 12 + i * 28;
        let f = |at: usize| f32::from_le_bytes(bytes[o + at..o + at + 4].try_into().unwrap());
        let color = [
            bytes[o + 24] as f32 / 255.,
            bytes[o + 25] as f32 / 255.,
            bytes[o + 26] as f32 / 255.,
            bytes[o + 27] as f32 / 255.,
        ];
        mesh.vertices.push(WorldVertex::with_meta(
            Vec3::new(f(0), f(4), f(8)),
            Vec3::new(f(12), f(16), f(20)),
            color,
            VertexMeta::DEFAULT,
        ));
    }
    for i in 0..n {
        let o = 12 + v * 28 + i * 2;
        mesh.indices
            .push(u16::from_le_bytes(bytes[o..o + 2].try_into().unwrap()) as u32);
    }
    validate_converted(name, &mesh)?;
    Ok(Prototype { mesh })
}

/// The converter removes faces whose minimum height is below `1e-7` meters.
/// `MeshBuffer::validate` deliberately uses a much larger general-purpose
/// threshold suited to hand-authored runtime geometry; applying it here
/// rejects legitimate, checked-in detail on the shopping cart after f32
/// packing.  Keep the loader's structural validation aligned with the
/// converter without changing any generated bytes.
fn validate_converted(name: &str, mesh: &MeshBuffer) -> Result<(), String> {
    for (index, vertex) in mesh.vertices.iter().enumerate() {
        let position = Vec3::from_array(vertex.position);
        let normal = Vec3::from_array(vertex.normal);
        if !position.is_finite()
            || !normal.is_finite()
            || !vertex.color.iter().all(|v| v.is_finite())
        {
            return Err(format!("{name}: non-finite vertex {index}"));
        }
        if (normal.length() - 1.0).abs() > 1e-2 {
            return Err(format!("{name}: unnormalized normal at vertex {index}"));
        }
    }
    for (triangle, indices) in mesh.indices.chunks_exact(3).enumerate() {
        let (a, b, c) = (indices[0], indices[1], indices[2]);
        let vertex_count = mesh.vertices.len();
        if [a, b, c]
            .iter()
            .any(|&index| index as usize >= vertex_count)
        {
            return Err(format!("{name}: out-of-range index in triangle {triangle}"));
        }
        let p0 = Vec3::from_array(mesh.vertices[a as usize].position);
        let p1 = Vec3::from_array(mesh.vertices[b as usize].position);
        let p2 = Vec3::from_array(mesh.vertices[c as usize].position);
        // This is cross-length²; 1e-20 permits converter-approved fine detail
        // while still rejecting a zero-area encoded triangle.
        if (p1 - p0).cross(p2 - p0).length_squared() <= 1e-20 {
            return Err(format!("{name}: degenerate triangle {triangle}"));
        }
    }
    Ok(())
}

macro_rules! assets {
    ($($id:ident => $path:literal),* $(,)?) => {
        $(const $id: &[u8] = include_bytes!(concat!("../../../../assets/living-buildings/converted/", $path));)*

        fn converted() -> BTreeMap<&'static str, Prototype> {
            [$({
                let key = $path.strip_suffix(".mesh").unwrap();
                (key, decode(key, $id).expect("checked-in prop mesh"))
            }),*].into_iter().collect()
        }
    }
}

