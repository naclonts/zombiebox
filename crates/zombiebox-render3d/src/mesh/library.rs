/// Shared, bottom-centered render prototypes for the stable gameplay catalog.
#[derive(Debug)]
pub struct PropMeshLibrary {
    prototypes: BTreeMap<&'static str, Prototype>,
}

impl PropMeshLibrary {
    pub fn shared() -> &'static Self {
        static LIBRARY: OnceLock<PropMeshLibrary> = OnceLock::new();
        LIBRARY.get_or_init(Self::builtin)
    }

    pub fn builtin() -> Self {
        let mut prototypes = converted();
        for (id, mesh) in [
            (PropId::GondolaShelf, kit::build_gondola_shelf(2)),
            (PropId::FuelPump, kit::build_fuel_pump()),
            (PropId::FuelPylon, kit::build_fuel_pylon()),
            (PropId::CheckoutLane, kit::build_checkout_lane(2)),
            // The converted `television-vintage` asset is a microwave, so the
            // Television key is served by a procedural CRT instead.
            (PropId::Television, kit::build_crt_television()),
            (PropId::TvStand, kit::build_tv_stand()),
            (PropId::Nightstand, kit::build_nightstand()),
            (PropId::Sign, signage::build_sign("BIRCH →", 0.96)),
            (PropId::GrocerySign, signage::build_sign("GROCERY", 1.9)),
            (PropId::RestroomSign, signage::build_sign("WC", 0.65)),
            (PropId::AisleSign, signage::build_sign("AISLES", 0.9)),
            (PropId::Note, signage::build_sign("NOTE", 0.42)),
            (PropId::Journal, signage::build_sign("LOG", 0.48)),
        ] {
            prototypes.insert(id.stem(), Prototype { mesh });
        }
        // The same factor scales gameplay bounds and imported or procedural meshes.
        // Closed/open variants must share the factor and pivot.
        let mut scaled = std::collections::BTreeSet::new();
        for &id in PropId::ALL {
            for state in [PropState::Closed, PropState::Opened] {
                let key = Self::asset_key(id, state);
                if scaled.insert(key) {
                    if let Some(prototype) = prototypes.get_mut(key) {
                        for vertex in &mut prototype.mesh.vertices {
                            for coordinate in &mut vertex.position {
                                *coordinate *= id.presentation_scale();
                            }
                        }
                    }
                }
            }
        }
        Self { prototypes }
    }

    pub fn iter(&self) -> impl Iterator<Item = (&'static str, &Prototype)> {
        self.prototypes
            .iter()
            .map(|(&key, prototype)| (key, prototype))
    }

    pub fn get(&self, id: PropId, state: PropState) -> Option<&MeshBuffer> {
        self.prototypes
            .get(Self::asset_key(id, state))
            .map(|p| &p.mesh)
    }

    pub fn asset_key(id: PropId, state: PropState) -> &'static str {
        match (id, state) {
            (PropId::Desk, PropState::Closed) => "desk-closed",
            (PropId::Desk, PropState::Opened) => "desk-opened",
            (PropId::Fridge, PropState::Closed) => "kitchen-fridge-closed",
            (PropId::Fridge, PropState::Opened) => "kitchen-fridge-opened",
            (PropId::CardboardBox, PropState::Closed) => "cardboard-box-closed",
            (PropId::CardboardBox, PropState::Opened) => "cardboard-box-opened",
            (PropId::CheckoutTill, PropState::Closed) => "assisted-checkout-till-closed",
            (PropId::CheckoutTill, PropState::Opened) => "assisted-checkout-till-opened",
            _ => id.stem(),
        }
    }

    pub fn transform(view: &PropView) -> Mat4 {
        Mat4::from_translation(sim_to_render_point(view.world_pivot))
            * Mat4::from_rotation_y(Self::yaw(view.facing))
    }

    pub const fn yaw(facing: PropFacing) -> f32 {
        match facing {
            PropFacing::South => 0.0,
            PropFacing::East => std::f32::consts::FRAC_PI_2,
            PropFacing::North => std::f32::consts::PI,
            PropFacing::West => -std::f32::consts::FRAC_PI_2,
        }
    }
}
