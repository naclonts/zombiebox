#!/usr/bin/env node
// Writes apps/mobile/gitInfo.ts, the build stamp shown in the in-game settings menu.
// Gradle and `npm ci` (postinstall) run this so the stamp matches the checkout
// the bundle was built from. The output file is generated, not tracked.
const {execFileSync} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const mobileDir = path.resolve(__dirname, '..');
const outputPath = path.join(mobileDir, 'gitInfo.ts');

function git(args) {
  return execFileSync('git', ['-C', mobileDir, ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim();
}

let commit = 'unknown';
let commitFull = 'unknown';
let dirty = false;
try {
  commitFull = git(['rev-parse', 'HEAD']);
  commit = git(['rev-parse', '--short=7', 'HEAD']);
  // Tracked changes only: generated and ignored build output must not mark the build dirty.
  dirty = git(['status', '--porcelain', '--untracked-files=no']).length > 0;
} catch {
  // Not a git checkout (for example a source tarball): keep the unknown stamp.
}

const contents = [
  '// Generated by scripts/write-git-info.cjs. Do not edit; run `npm run git-info`.',
  `export const GIT_COMMIT = ${JSON.stringify(commit)};`,
  `export const GIT_COMMIT_FULL = ${JSON.stringify(commitFull)};`,
  `export const GIT_COMMIT_DIRTY = ${dirty};`,
  `export const BUILD_STAMP = ${JSON.stringify(`BUILD ${commit}${dirty ? '-dirty' : ''}`)};`,
  '',
].join('\n');

const current = fs.existsSync(outputPath)
  ? fs.readFileSync(outputPath, 'utf8')
  : null;
if (current !== contents) {
  fs.writeFileSync(outputPath, contents);
}
